"""Offline negative tests; the full pip-compile rerun is separately required in WSL."""
import importlib.util
from pathlib import Path

import pytest

MODULE = Path(__file__).resolve().parents[1] / 'tools' / 'check_lock_graph.py'
spec = importlib.util.spec_from_file_location('check_lock_graph', MODULE)
module = importlib.util.module_from_spec(spec)
import sys
sys.modules[spec.name] = module
spec.loader.exec_module(module)

LockError = module.LockError

ONE = 'a' * 64
TWO = 'b' * 64
THREE = 'c' * 64


def dirs():
    data = '\n'.join(f'package-{i}==1.0' for i in range(11))+'\n'
    return data.encode()


def lock(python='3.13', extra='', variant=''):
    rows = [f'# This file is autogenerated by pip-compile with Python {python}', '# by the following command:']
    for i in range(11):
        rows.extend([f'package-{i}==1.0 \\',f'    --hash=sha256:{ONE}'])
    if extra:
        rows.extend([f'{extra}==4.16.0 \\',f'    --hash=sha256:{TWO}'])
    if variant:
        rows.extend([f'transitive=={variant} \\',f'    --hash=sha256:{THREE}'])
    else:
        rows.extend(['transitive==2.0 \\',f'    --hash=sha256:{THREE}'])
    return ('\n'.join(rows)+'\n').encode()


def verify(committed=None, independent=None, prod=None, direct=None, python='3.13'):
    expected = lock() if committed is None else committed
    ref = lock() if independent is None else independent
    return module.verify(dirs() if prod is None else prod, dirs() if direct is None else direct, expected, ref, python)


def test_positive_reference():
    assert verify() == 12


def test_python_312_positive():
    assert verify(lock('3.12', 'typing-extensions'), lock('3.12', 'typing-extensions'), python='3.12') == 13


def test_typing_extensions_superfluous_313():
    with pytest.raises(LockError, match='unexpected.*typing-extensions'):
        verify(lock(extra='typing-extensions'))


def test_missing_transitive():
    with pytest.raises(LockError, match='missing from committed lock: transitive'):
        verify(lock().replace((f'transitive==2.0 \\\n    --hash=sha256:{THREE}\n').encode(), b''))


def test_older_still_compatible_version_detected_against_regenerated():
    with pytest.raises(LockError, match='transitive: version 1.0 != 2.0'):
        verify(lock(variant='1.0'))


def test_hash_mismatch():
    with pytest.raises(LockError, match='SHA256 set differs'):
        verify(lock().replace(THREE.encode(), TWO.encode()))


def test_missing_hash_fails_closed():
    with pytest.raises(LockError, match='missing SHA256'):
        verify(lock().replace(f'    --hash=sha256:{THREE}\n'.encode(), b''))


def test_duplicate_package_rejected():
    with pytest.raises(LockError, match='duplicate package'):
        verify(lock() + f'transitive==2.0 \\\n    --hash=sha256:{THREE}\n'.encode())


def test_unapproved_index_directive_rejected():
    with pytest.raises(LockError, match='directives not permitted'):
        verify(lock() + b'--extra-index-url https://other.example/simple\n')


def test_production_input_divergence_detected():
    with pytest.raises(LockError, match='differ byte-for-byte'):
        verify(prod=dirs().replace(b'package-0==1.0', b'package-0==2.0'))


def test_python_header_mismatch_detected():
    with pytest.raises(LockError, match='expected a unique Python 3.13'):
        verify(lock('3.12'))


def test_hash_comment_reordering_ignored():
    raw=lock(); alternate=raw.replace(b'# by the following command:', b'# alternate generator command')
    assert verify(alternate, raw) == 12


def test_extras_semantically_compared():
    expected=lock().replace(b'transitive==2.0', b'transitive[fast]==2.0')
    with pytest.raises(LockError, match='extras'):
        verify(expected)


def test_marker_semantically_compared():
    expected=lock().replace(b'transitive==2.0 \\', b'transitive==2.0 ; python_version >= "3.12" \\')
    with pytest.raises(LockError, match='marker'):
        verify(expected)


def test_invalid_direct_marker_fails_closed():
    with pytest.raises(LockError, match='one exact unmarked pin'):
        verify(direct=dirs().replace(b'package-0==1.0', b'package-0==1.0; python_version > "3.11"'), prod=dirs().replace(b'package-0==1.0', b'package-0==1.0; python_version > "3.11"'))
