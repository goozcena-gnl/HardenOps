#!/usr/bin/env python3
"""Strict, side-effect-free comparison of pip-compile locks against an independent rebuild.

This compares semantic entries (name, version, extras, marker, complete SHA256 set),
not comment formatting. It cannot alone establish that a resolver computed a correct
closure: the reference MUST be produced independently under the intended Python.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from packaging.requirements import InvalidRequirement, Requirement
from packaging.utils import canonicalize_name

HASH_LINE = re.compile(r"--hash=sha256:([a-fA-F0-9]{64})")
HEADER = re.compile(r"^# This file is autogenerated by pip-compile with Python (3\.\d{2})\s*$", re.M)
EXACT_VERSION = re.compile(r"^==([^*\s]+)$")


class LockError(ValueError):
    """Invalid lock or a non-matching independent resolution."""


@dataclass(frozen=True)
class Package:
    version: str
    extras: tuple[str, ...]
    marker: str
    hashes: frozenset[str]


def parse_pins(raw: bytes) -> dict[str, str]:
    """Parse the 11 exact direct pins. Any unsupported syntax fails closed."""
    out: dict[str, str] = {}
    for i, line in enumerate(raw.decode('utf-8').splitlines(), 1):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        try:
            req = Requirement(s)
        except InvalidRequirement as exc:
            raise LockError(f'direct line {i}: invalid requirement: {exc}') from exc
        match = EXACT_VERSION.fullmatch(str(req.specifier))
        if not match or req.marker or req.url or req.extras:
            raise LockError(f'direct line {i}: expected one exact unmarked pin')
        name = canonicalize_name(req.name)
        if name in out:
            raise LockError(f'direct line {i}: duplicated package {name}')
        out[name] = match.group(1)
    if len(out) != 11:
        raise LockError(f'expected 11 direct pins, got {len(out)}')
    return out


def parse_lock(data: bytes, python_version: str) -> dict[str, Package]:
    text = data.decode('utf-8')
    headers = HEADER.findall(text)
    if len(headers) != 1 or headers[0] != python_version:
        raise LockError(f'expected a unique Python {python_version} pip-compile header; got {headers}')
    raw_packages: dict[str, tuple[str, tuple[str, ...], str, set[str]]] = {}
    current: str | None = None
    for line_number, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        if s.endswith('\\'):
            s = s[:-1].rstrip()
        if s.startswith('--hash='):
            m = HASH_LINE.fullmatch(s)
            if not m or current is None:
                raise LockError(f'line {line_number}: unexpected or malformed hash')
            h = m.group(1).lower()
            values = raw_packages[current][3]
            if h in values:
                raise LockError(f'line {line_number}: duplicate hash for {current}')
            values.add(h)
            continue
        if s.startswith('-'):
            raise LockError(f'line {line_number}: directives not permitted: {s[:60]}')
        try:
            req = Requirement(s)
        except InvalidRequirement as exc:
            raise LockError(f'line {line_number}: invalid requirement: {exc}') from exc
        version = EXACT_VERSION.fullmatch(str(req.specifier))
        if not version or req.url:
            raise LockError(f'line {line_number}: requirement must be pinned exactly')
        name = canonicalize_name(req.name)
        if name in raw_packages:
            raise LockError(f'line {line_number}: duplicate package {name}')
        extras = tuple(sorted(canonicalize_name(e) for e in req.extras))
        marker = str(req.marker) if req.marker else ''
        raw_packages[name] = (version.group(1), extras, marker, set())
        current = name
    result = {}
    for name, (version, extras, marker, hashes) in raw_packages.items():
        if not hashes:
            raise LockError(f'missing SHA256 for {name}')
        result[name] = Package(version, extras, marker, frozenset(hashes))
    if not result:
        raise LockError('empty lock')
    return result


def compare(expected: dict[str, Package], reference: dict[str, Package]) -> None:
    unexpected = sorted(set(expected) - set(reference))
    missing = sorted(set(reference) - set(expected))
    mismatches = [name for name in sorted(set(reference) & set(expected)) if expected[name] != reference[name]]
    if unexpected or missing or mismatches:
        problems = []
        if unexpected:
            problems.append('unexpected in committed lock: ' + ', '.join(unexpected))
        if missing:
            problems.append('missing from committed lock: ' + ', '.join(missing))
        for n in mismatches:
            lhs, rhs = expected[n], reference[n]
            if lhs.version != rhs.version:
                problems.append(f'{n}: version {lhs.version} != {rhs.version}')
            if lhs.extras != rhs.extras:
                problems.append(f'{n}: extras {lhs.extras} != {rhs.extras}')
            if lhs.marker != rhs.marker:
                problems.append(f'{n}: marker {lhs.marker!r} != {rhs.marker!r}')
            if lhs.hashes != rhs.hashes:
                problems.append(f'{n}: SHA256 set differs')
        raise LockError('; '.join(problems))


def verify(direct_txt: bytes, direct_in: bytes, committed: bytes, independent: bytes, python: str) -> int:
    if direct_txt != direct_in:
        raise LockError('requirements-dev.txt and requirements-dev.in differ byte-for-byte')
    direct = parse_pins(direct_in)
    current = parse_lock(committed, python)
    reference = parse_lock(independent, python)
    for graph_name, graph in [('committed', current), ('independent', reference)]:
        for name, version in direct.items():
            if name not in graph or graph[name].version != version:
                raise LockError(f'{graph_name} lock direct pin mismatch: {name}=={version}')
    compare(current, reference)
    return len(current)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--python', required=True, choices=['3.12', '3.13'])
    p.add_argument('--lock', type=Path, required=True)
    p.add_argument('--independent', type=Path, required=True)
    p.add_argument('--direct', type=Path, default=Path('requirements-dev.in'))
    p.add_argument('--production', type=Path, default=Path('requirements-dev.txt'))
    a = p.parse_args()
    try:
        count = verify(a.production.read_bytes(), a.direct.read_bytes(), a.lock.read_bytes(), a.independent.read_bytes(), a.python)
    except (LockError, UnicodeDecodeError, OSError) as exc:
        print(f'LOCK GRAPH FAIL [Python {a.python}]: {exc}', file=sys.stderr)
        return 1
    print(f'LOCK GRAPH PASS [Python {a.python}]: {count} packages, exact pins/extras/markers/SHA256 sets')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
